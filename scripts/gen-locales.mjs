// Writes hooks/locales/index.ts, the registry of languages, from the locale files beside it
// (run: pnpm locales; pnpm bundle runs it too). A locale file is `<code>.ts`, two or three lower-case
// letters, exporting `defineLocale({ code, names, strings })` as default. The board mod cannot list
// a folder or import at run time, so the registry is plain imports.
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const LOCALE_FILE = /^([a-z]{2,3})\.ts$/;

/** The registry's text for the locale files in `dir`. */
export function localeIndex(dir) {
  const codes = readdirSync(dir)
    .flatMap((name) => LOCALE_FILE.exec(name)?.[1] ?? [])
    .sort();
  const id = (code) => `locale_${code}`;
  return [
    '// Generated by scripts/gen-locales.mjs from the locale files in this folder. Do not edit:',
    '// add or remove a <code>.ts file and run pnpm locales (pnpm bundle runs it too).',
    "import type { Locale } from '../i18n/messages.js';",
    ...codes.map((c) => `import ${id(c)} from './${c}.js';`),
    '',
    `export const LOCALES: readonly Locale[] = [${codes.map(id).join(', ')}];`,
    '',
  ].join('\n');
}

export function writeLocaleIndex(dir) {
  writeFileSync(join(dir, 'index.ts'), localeIndex(dir));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeLocaleIndex(process.argv[2] ?? join(import.meta.dirname, '..', 'hooks', 'locales'));
}
