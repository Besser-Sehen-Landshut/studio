// Generates src/rea-schemas.ts from the pinned REA server's tool list (MCP `tools/list`).
//
//   node scripts/gen-rea-schemas.mjs --tools <tools.json>    from a saved `tools/list` result
//   node scripts/gen-rea-schemas.mjs --server <rea.mjs>      asks an installed server itself
//   ... --out <file>                                          writes elsewhere (tests)
//
// `--server` takes the installed package's command (the `entry` of `studio doctor`'s install, below
// the owner state's rea/<version>/) and starts it with `mcp` in an empty temporary directory with a
// minimal environment (PATH only, a temporary HOME and TMPDIR, no npm config). Review the diff of
// src/rea-schemas.ts before committing; then run `npx biome check --write src/rea-schemas.ts`.
//
// The classification is type-aware: only string arguments (or arrays of strings) can name a place
// or be free text. A number such as `max_semantic_nodes_per_file` is neither.
import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** A string argument whose name ends in one of these words names a place on disk. */
const PATH_LAST = new Set(['path', 'paths', 'root', 'roots', 'directory', 'executable', 'tty']);
/** ... or whose name holds one of these words anywhere. */
const PATH_ANY = new Set(['file', 'files', 'dir']);
/** Free-text arguments (a search term, a symbol or class name): never read as places. */
const TEXT = new Set([
  'class_name',
  'decoder',
  'display_filter',
  'filter',
  'key',
  'mask',
  'method_name',
  'name',
  'pattern',
  'query',
  'selector',
  'symbols',
  'type_names',
]);

/** The JSON Schema types a property may take, flattened over anyOf/oneOf and arrays' items. */
function kinds(schema) {
  if (schema === null || typeof schema !== 'object') return [];
  const alt = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(alt)) return alt.flatMap(kinds);
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  return types.flatMap((t) => (t === 'array' ? kinds(schema.items).map((k) => `array:${k}`) : [t]));
}

/** Only strings, arrays of strings and null: anything else (numbers, objects) is not text. */
export function isStringy(schema) {
  const k = kinds(schema).filter((t) => t !== 'null' && t !== undefined);
  return k.length > 0 && k.every((t) => t === 'string' || t === 'array:string');
}

const words = (name) =>
  name
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((w) => w !== '');

export function isPathArg(name, schema) {
  if (!isStringy(schema)) return false;
  const w = words(name);
  return PATH_LAST.has(w.at(-1) ?? '') || w.some((x) => PATH_ANY.has(x));
}

export function isTextArg(name, schema) {
  return isStringy(schema) && TEXT.has(name);
}

/** `{ <tool>: { keys, paths, text } }` for a `tools/list` result, keys sorted. */
export function classify(tools) {
  const out = {};
  for (const t of [...tools].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const props = t.inputSchema?.properties ?? {};
    const keys = Object.keys(props).sort();
    out[t.name] = {
      keys,
      paths: keys.filter((k) => isPathArg(k, props[k])),
      text: keys.filter((k) => isTextArg(k, props[k])),
    };
  }
  return out;
}

export function render(schemas, version) {
  const list = (a) => `[${a.map((x) => `'${x}'`).join(', ')}]`;
  const body = Object.entries(schemas)
    .map(
      ([n, s]) =>
        `  ${n}: { keys: ${list(s.keys)}, paths: ${list(s.paths)}, text: ${list(s.text)} },`,
    )
    .join('\n');
  return `// Generated by scripts/gen-rea-schemas.mjs from the tool list of rea-agents ${version}
// (tools/list, inputSchema.properties). Do not edit by hand: regenerate when the pin moves and
// review the diff; a tool that is not here is denied.
// keys:  the top-level argument names a tool accepts; the guard refuses any other.
// paths: string arguments that name a place on disk; their strings are always resolved and confined.
// text:  free-text string arguments (a search term, a name) that are not read as places.
export interface ReaToolSchema {
  keys: readonly string[];
  paths: readonly string[];
  text: readonly string[];
}
export const REA_TOOL_SCHEMAS: Readonly<Record<string, ReaToolSchema>> = {
${body}
};
`;
}

async function fromServer(entry) {
  const dir = mkdtempSync(join(tmpdir(), 'rea-schemas-'));
  try {
    return await new Promise((resolve, reject) => {
      const cp = spawn(process.execPath, [entry, 'mcp'], {
        cwd: dir,
        env: {
          PATH: process.env.PATH ?? '/usr/bin:/bin',
          HOME: dir,
          TMPDIR: dir,
          npm_config_userconfig: '/dev/null',
          npm_config_globalconfig: '/dev/null',
        },
        stdio: ['pipe', 'pipe', 'inherit'],
      });
      const timer = setTimeout(() => {
        cp.kill();
        reject(new Error('the server did not answer within 120 s'));
      }, 120_000);
      let buf = '';
      const send = (m) => cp.stdin.write(`${JSON.stringify(m)}\n`);
      cp.stdout.on('data', (d) => {
        buf += d;
        for (let i = buf.indexOf('\n'); i >= 0; i = buf.indexOf('\n')) {
          const m = JSON.parse(buf.slice(0, i));
          buf = buf.slice(i + 1);
          if (m.id === 1) {
            send({ jsonrpc: '2.0', method: 'notifications/initialized' });
            send({ jsonrpc: '2.0', id: 2, method: 'tools/list' });
          } else if (m.id === 2) {
            clearTimeout(timer);
            cp.kill();
            resolve({ tools: m.result.tools, version: m.serverInfo?.version });
          }
        }
      });
      cp.on('error', reject);
      send({
        jsonrpc: '2.0',
        id: 1,
        method: 'initialize',
        params: {
          protocolVersion: '2025-06-18',
          capabilities: {},
          clientInfo: { name: 'studio-gen-rea-schemas', version: '0' },
        },
      });
    });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [flag, arg, outFlag, outArg] = process.argv.slice(2);
  if (
    (flag !== '--tools' && flag !== '--server') ||
    arg === undefined ||
    (outFlag !== undefined && (outFlag !== '--out' || outArg === undefined))
  ) {
    process.stderr.write(
      'usage: gen-rea-schemas.mjs --tools <tools.json> | --server <rea.mjs> [--out <file>]\n',
    );
    process.exit(2);
  }
  const reaTs = readFileSync(fileURLToPath(new URL('../src/rea.ts', import.meta.url)), 'utf8');
  const version = /REA_DEFAULT_VERSION = '([^']+)'/.exec(reaTs)?.[1] ?? 'the pinned version';
  const tools =
    flag === '--tools'
      ? JSON.parse(readFileSync(arg, 'utf8')).tools
      : (await fromServer(arg)).tools;
  const out = outArg ?? fileURLToPath(new URL('../src/rea-schemas.ts', import.meta.url));
  writeFileSync(out, render(classify(tools), version));
  process.stdout.write(`${tools.length} tools written to ${out}\n`);
}
