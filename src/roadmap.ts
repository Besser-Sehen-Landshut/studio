import { readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { type Board, type Epic, epicProgress, epicSchema, type WorkItem } from './board.js';
import { byEpicId, nextEpicId } from './epics.js';

export const ROADMAP_HEADER = '<!-- generated by studio roadmap; edit the board, not this file -->';

const ACTIVE: readonly WorkItem['status'][] = ['assigned', 'in_progress', 'in_review', 'queued'];

/** Natural id order: APP-2 before APP-10. */
function compareIds(a: string, b: string): number {
  const pa = /^(.*?)(\d+)$/.exec(a);
  const pb = /^(.*?)(\d+)$/.exec(b);
  if (pa && pb && pa[1] === pb[1]) return Number(pa[2]) - Number(pb[2]);
  return a < b ? -1 : a > b ? 1 : 0;
}

function epicBox(board: Board, epic: Epic): string {
  if (epic.status === 'done') return '[x]';
  if (epic.status === 'accepting') return '[~]';
  return board.items.some((i) => i.epic === epic.id && ACTIVE.includes(i.status)) ? '[~]' : '[ ]';
}

const itemBox = (i: WorkItem): string =>
  i.status === 'merged' ? '[x]' : ACTIVE.includes(i.status) ? '[~]' : '[ ]';

/**
 * The roadmap as markdown, from the board alone: epics in id order (dropped ones left out) with
 * goal and acceptance, then the open items that belong to no epic. Review items are the review of
 * another item and stay out. Deterministic: the same board gives the same text.
 */
export function renderRoadmap(board: Board): string {
  const out: string[] = [ROADMAP_HEADER, '', '# Roadmap', ''];
  const epics = [...(board.epics ?? [])].filter((e) => e.status !== 'dropped').sort(byEpicId);
  for (const e of epics) {
    const p = epicProgress(board, e.id);
    out.push(`- ${epicBox(board, e)} ${e.id} — ${e.title} (${p.merged}/${p.total})`);
    out.push(`  - Goal: ${e.goal}`);
    out.push('  - Acceptance:');
    for (const a of e.acceptance) out.push(`    - ${a}`);
  }
  const loose = board.items.filter((i) => i.epic === undefined && i.type !== 'review');
  const open = loose
    .filter((i) => i.status !== 'merged' && i.status !== 'dropped')
    .sort((a, b) => compareIds(a.id, b.id));
  const merged = loose.filter((i) => i.status === 'merged').length;
  if (open.length > 0 || merged > 0) {
    if (epics.length > 0) out.push('');
    out.push('## Not in an epic', '');
    for (const i of open) out.push(`- ${itemBox(i)} ${i.id} — ${i.title}`);
    if (merged > 0) out.push(`- ${merged} merged ${merged === 1 ? 'item' : 'items'} not shown`);
  }
  if (epics.length === 0 && open.length === 0 && merged === 0) out.push('Nothing planned yet.');
  return `${out.join('\n')}\n`;
}

/** A path relative to the project that stays inside it, else an error. */
export function projectFile(project: string, file: string): string {
  if (file === '' || isAbsolute(file) || /^[A-Za-z]:/.test(file)) {
    throw new Error(`${JSON.stringify(file)}: give a path relative to the project`);
  }
  const full = resolve(project, file);
  const rel = relative(project, full);
  if (rel === '' || rel.startsWith('..') || rel.split(sep).includes('..')) {
    throw new Error(`${JSON.stringify(file)}: must stay inside the project`);
  }
  return full;
}

/**
 * Writes the roadmap through a temporary file and a rename. Refuses a file that exists and does
 * not start with the generated header, unless `force`: that one was written by hand.
 */
export function writeRoadmap(
  project: string,
  out: string,
  text: string,
  force: boolean,
): { written: string; changed: boolean } {
  const file = projectFile(project, out);
  let old: string | undefined;
  try {
    old = readFileSync(file, 'utf8');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'ENOENT') throw e;
  }
  if (old !== undefined && !old.startsWith(ROADMAP_HEADER) && !force) {
    throw new Error(
      `${out} was not generated by studio roadmap: import its phases with studio roadmap import ${out}, or overwrite it with --force`,
    );
  }
  if (old === text) return { written: out, changed: false };
  const tmp = join(file, '..', `.${process.pid}.${Date.now()}.roadmap.tmp`);
  try {
    writeFileSync(tmp, text, { flag: 'wx' });
    renameSync(tmp, file);
  } catch (err) {
    rmSync(tmp, { force: true });
    throw err;
  }
  return { written: out, changed: true };
}

export type Phase = { phase: string; box: ' ' | '~' | 'x'; title: string; goal: string };

const LINE = /^\s*[-*+]\s+\[([ xX~])\]\s+(.*)$/;
const PHASE = /^phase\s+(\d+(?:\.\d+)*[a-z]?)(?=$|[\s:—–-])\s*(?:[—–:-]+\s*)?(.*)$/i;
const SPLIT = /\s+[—–-]\s+|:\s+/;

const clean = (s: string): string => s.replace(/[\p{Cc}\p{Cf}]/gu, '').trim();
const capped = (s: string, n: number): string => {
  const cps = [...s];
  return cps.length <= n ? s : `${cps.slice(0, n - 1).join('')}…`;
};

/**
 * The phase lines of a hand-written roadmap: `- [ ] Phase <n> — <title>`, with `[~]` or `[x]`,
 * any of `-`, `–`, `—` or `:` after the number, bold markers, and trailing tags such as
 * `@claim:<session>` or an HTML comment dropped. The title is the text up to the next separator,
 * the goal what follows it (or the title again when nothing does).
 */
export function parsePhases(text: string): Phase[] {
  const out: Phase[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = LINE.exec(raw);
    if (!line) continue;
    const body = clean((line[2] as string).replace(/\*\*|__/g, ''));
    const m = PHASE.exec(body);
    if (!m) continue;
    let rest = (m[2] as string).replace(/\s*<!--.*?-->\s*/g, ' ').trim();
    for (;;) {
      const next = rest.replace(/\s*(?:^|\s)@[\w.-]+(?::\S*)?$/, '').trim();
      if (next === rest) break;
      rest = next;
    }
    rest = rest.replace(/[\s—–:-]+$/, '');
    const phase = m[1] as string;
    const cut = SPLIT.exec(rest);
    const title = cut ? rest.slice(0, cut.index).trim() : rest;
    const after = cut ? rest.slice(cut.index + cut[0].length).trim() : '';
    const name = title === '' ? `Phase ${phase}` : title;
    out.push({
      phase,
      box: (line[1] as string).toLowerCase() as Phase['box'],
      title: capped(name, 300),
      goal: capped(after === '' ? name : after, 2000),
    });
  }
  return out;
}

export type ImportPlan = {
  file: string;
  create: Epic[];
  skipped: { phase: string; reason: string }[];
};

/**
 * What `roadmap import` adds: one epic per phase not yet imported from `source` (by its
 * `imported_from`), with the next free ids. Pure; no items are created.
 */
export function planImport(board: Board, source: string, phases: Phase[]): ImportPlan {
  const seen = new Set((board.epics ?? []).flatMap((e) => e.importedFrom ?? []));
  const inFile = new Set<string>();
  const create: Epic[] = [];
  const skipped: ImportPlan['skipped'] = [];
  let next = Number(nextEpicId(board).slice(2));
  for (const p of phases) {
    const from = `${source}#Phase ${p.phase}`;
    if (inFile.has(p.phase)) {
      skipped.push({ phase: p.phase, reason: 'the phase number comes twice in the file' });
      continue;
    }
    inFile.add(p.phase);
    if (seen.has(from)) {
      skipped.push({ phase: p.phase, reason: 'imported already' });
      continue;
    }
    create.push(
      epicSchema.parse({
        id: `E-${next++}`,
        title: p.title,
        status: p.box === 'x' ? 'done' : 'open',
        goal: p.goal,
        acceptance: ['imported from ROADMAP: define acceptance'],
        importedFrom: from,
        history: [],
      }),
    );
  }
  return { file: source, create, skipped };
}
