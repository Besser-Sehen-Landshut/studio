import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { type Board, parseBoard } from '../src/board.js';
import {
  parsePhases,
  planImport,
  ROADMAP_HEADER,
  renderRoadmap,
  writeRoadmap,
} from '../src/roadmap.js';

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});
const tmp = () => {
  const d = mkdtempSync(join(tmpdir(), 'studio-roadmap-'));
  dirs.push(d);
  return d;
};

const it_ = (id: string, status: string, extra = '', type = 'fix') =>
  `  - { id: ${id}, title: Item ${id}, type: ${type}, role: builder, repo: org/app, size: S, priority: 1, status: ${status}${extra} }`;
const ep = (id: string, status: string, title: string) =>
  `  - { id: ${id}, title: ${title}, status: ${status}, goal: Goal of ${id}, acceptance: [first check, second check] }`;

const BOARD: Board = parseBoard(
  [
    'items:',
    it_('APP-10', 'ready'),
    it_('APP-2', 'in_progress'),
    it_('APP-3', 'merged', ', epic: E-1'),
    it_('APP-4', 'in_review', ', epic: E-1'),
    it_('APP-5', 'ready', ', epic: E-1'),
    it_('APP-6', 'dropped', ', epic: E-1'),
    it_('APP-7', 'merged', ', epic: E-2'),
    it_('APP-8', 'merged'),
    it_('APP-9', 'ready', '', 'review'),
    it_('APP-11', 'ready', ', epic: E-10'),
    'epics:',
    ep('E-10', 'open', 'Later work'),
    ep('E-2', 'accepting', 'Invoices'),
    ep('E-1', 'open', 'Checkout'),
    ep('E-3', 'done', 'Imported'),
    ep('E-4', 'dropped', 'Abandoned'),
    '',
  ].join('\n'),
  'board.yaml',
);

describe('studio roadmap renders the board', () => {
  it('renders epics in id order with progress, then open items without an epic', () => {
    expect(renderRoadmap(BOARD)).toBe(
      [
        ROADMAP_HEADER,
        '',
        '# Roadmap',
        '',
        '- [~] E-1 — Checkout (1/3)',
        '  - Goal: Goal of E-1',
        '  - Acceptance:',
        '    - first check',
        '    - second check',
        '- [~] E-2 — Invoices (1/1)',
        '  - Goal: Goal of E-2',
        '  - Acceptance:',
        '    - first check',
        '    - second check',
        '- [x] E-3 — Imported (0/0)',
        '  - Goal: Goal of E-3',
        '  - Acceptance:',
        '    - first check',
        '    - second check',
        '- [ ] E-10 — Later work (0/1)',
        '  - Goal: Goal of E-10',
        '  - Acceptance:',
        '    - first check',
        '    - second check',
        '',
        '## Not in an epic',
        '',
        '- [~] APP-2 — Item APP-2',
        '- [ ] APP-10 — Item APP-10',
        '- 1 merged item not shown',
        '',
      ].join('\n'),
    );
  });

  it('is deterministic: the order of the board does not matter', () => {
    const shuffled: Board = {
      items: [...BOARD.items].reverse(),
      epics: [...(BOARD.epics ?? [])].reverse(),
    };
    expect(renderRoadmap(shuffled)).toBe(renderRoadmap(BOARD));
  });

  it('says so for an empty board', () => {
    expect(renderRoadmap({ items: [] })).toBe(
      `${ROADMAP_HEADER}\n\n# Roadmap\n\nNothing planned yet.\n`,
    );
  });
});

describe('roadmap --write', () => {
  it('writes a new file and replaces its own, through a temp file', () => {
    const dir = tmp();
    expect(writeRoadmap(dir, 'ROADMAP.md', `${ROADMAP_HEADER}\none\n`, false)).toEqual({
      written: 'ROADMAP.md',
      changed: true,
    });
    expect(writeRoadmap(dir, 'ROADMAP.md', `${ROADMAP_HEADER}\none\n`, false).changed).toBe(false);
    writeRoadmap(dir, 'ROADMAP.md', `${ROADMAP_HEADER}\ntwo\n`, false);
    expect(readFileSync(join(dir, 'ROADMAP.md'), 'utf8')).toBe(`${ROADMAP_HEADER}\ntwo\n`);
    expect(readdirSync(dir)).toEqual(['ROADMAP.md']);
  });

  it('refuses a hand-written file unless --force', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'ROADMAP.md'), '# My roadmap\n- [ ] Phase 1 — x\n');
    expect(() => writeRoadmap(dir, 'ROADMAP.md', `${ROADMAP_HEADER}\n`, false)).toThrow(
      /was not generated by studio roadmap.*--force/,
    );
    expect(readFileSync(join(dir, 'ROADMAP.md'), 'utf8')).toBe('# My roadmap\n- [ ] Phase 1 — x\n');
    writeRoadmap(dir, 'ROADMAP.md', `${ROADMAP_HEADER}\n`, true);
    expect(readFileSync(join(dir, 'ROADMAP.md'), 'utf8')).toBe(`${ROADMAP_HEADER}\n`);
  });

  it('writes only inside the project', () => {
    const dir = tmp();
    mkdirSync(join(dir, 'docs'));
    expect(writeRoadmap(dir, 'docs/ROADMAP.md', ROADMAP_HEADER, false).changed).toBe(true);
    expect(() => writeRoadmap(dir, '../ROADMAP.md', ROADMAP_HEADER, false)).toThrow(/inside/);
    expect(() => writeRoadmap(dir, '/tmp/ROADMAP.md', ROADMAP_HEADER, false)).toThrow(/relative/);
  });
});

const HAND_WRITTEN = `# Roadmap

Some prose that is no phase.

- [x] Phase 1 — Foundation: database and login
- [~] Phase 2 – Checkout redesign @claim:session-a
- [ ] Phase 3 - Invoices — customers pay by invoice @claim:session-b @owner
- [ ] **Phase 4: Reports** <!-- later -->
* [ ] Phase 4b — Exports
- [ ] Phase 5
- [ ] Phase 3 — the same number again
- [ ] Not a phase line
  - [ ] Phase 6 — nested is fine
`;

describe('roadmap import', () => {
  it('reads phase lines with mixed separators, boxes, bold and trailing tags', () => {
    expect(parsePhases(HAND_WRITTEN)).toEqual([
      { phase: '1', box: 'x', title: 'Foundation', goal: 'database and login' },
      { phase: '2', box: '~', title: 'Checkout redesign', goal: 'Checkout redesign' },
      { phase: '3', box: ' ', title: 'Invoices', goal: 'customers pay by invoice' },
      { phase: '4', box: ' ', title: 'Reports', goal: 'Reports' },
      { phase: '4b', box: ' ', title: 'Exports', goal: 'Exports' },
      { phase: '5', box: ' ', title: 'Phase 5', goal: 'Phase 5' },
      { phase: '3', box: ' ', title: 'the same number again', goal: 'the same number again' },
      { phase: '6', box: ' ', title: 'nested is fine', goal: 'nested is fine' },
    ]);
  });

  it('plans one epic per phase, open or done from the box, and is idempotent', () => {
    const board = parseBoard(`items: []\nepics:\n${ep('E-1', 'open', 'Existing')}\n`, 'b');
    const plan = planImport(board, 'ROADMAP.md', parsePhases(HAND_WRITTEN));
    expect(plan.create.map((e) => [e.id, e.status, e.title, e.importedFrom])).toEqual([
      ['E-2', 'done', 'Foundation', 'ROADMAP.md#Phase 1'],
      ['E-3', 'open', 'Checkout redesign', 'ROADMAP.md#Phase 2'],
      ['E-4', 'open', 'Invoices', 'ROADMAP.md#Phase 3'],
      ['E-5', 'open', 'Reports', 'ROADMAP.md#Phase 4'],
      ['E-6', 'open', 'Exports', 'ROADMAP.md#Phase 4b'],
      ['E-7', 'open', 'Phase 5', 'ROADMAP.md#Phase 5'],
      ['E-8', 'open', 'nested is fine', 'ROADMAP.md#Phase 6'],
    ]);
    expect(plan.create[0]?.acceptance).toEqual(['imported from ROADMAP: define acceptance']);
    expect(plan.skipped).toEqual([
      { phase: '3', reason: 'the phase number comes twice in the file' },
    ]);
    const after: Board = { ...board, epics: [...(board.epics ?? []), ...plan.create] };
    const again = planImport(after, 'ROADMAP.md', parsePhases(HAND_WRITTEN));
    expect(again.create).toEqual([]);
    expect(again.skipped.filter((s) => s.reason === 'imported already')).toHaveLength(7);
  });
});
